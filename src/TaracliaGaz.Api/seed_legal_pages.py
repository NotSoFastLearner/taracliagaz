def seed():
    db = SessionLocal()
    try:
        print("Создаю юридические страницы...")
        created_count = 0
        skipped_count = 0
        
        for slug, data in LEGAL_PAGES.items():
            existing = db.execute(
                select(Page).where(Page.slug == slug, Page.language_code == "ru")
            ).scalar_one_or_none()
            
            if existing:
                print(f"Страница '{slug}' уже существует (ID={existing.id}), пропускаю")
                skipped_count += 1
                continue
            
            page = Page(
                slug=slug,
                title=data["title"],
                body_html=data["body_html"].strip(),
                language_code="ru",
                is_published=True
            )
            db.add(page)
            created_count += 1
            print(f"Создана: /page/{slug} — {data['title']}")
        
        db.commit()
        print(f"\n Создано: {created_count}, пропущено: {skipped_count}")
        print("\n Доступные страницы:")
        print("   http://localhost:5173/page/privacy")
        print("   http://localhost:5173/page/terms")
        print("   http://localhost:5173/page/cookies")
    except Exception as e:
        db.rollback()
        print(f" Ошибка: {e}")
        raise
    finally:
        db.close()

if __name__ == "__main__":
    seed()